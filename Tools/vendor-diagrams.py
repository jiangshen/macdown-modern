#!/usr/bin/env python3
"""Reproduce pinned, self-contained diagram bundles and original distribution notices."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "Packages/SnowfolioCore/Sources/DiagramCore/Resources"
PACKAGES = {
    "mermaid": ("12.3.0", "https://registry.npmjs.org/mermaid/-/mermaid-12.3.0.tgz", "4113TdXeLAsMruJ79OpFL5O8+LTFXhQqZ260rF3tgUmiNAtRm4Uume04I+65PRN6yZ69J4f8rVYWW8zRk65UYw==", "package/dist/mermaid.min.js", "Mermaid.js"),
    "viz": ("3.31.0", "https://registry.npmjs.org/@viz-js/viz/-/viz-3.31.0.tgz", "r7zlQdRvcwvIpjHGgs+KNWHeE/P5/Dq7k8ZAKaMCbZqomxCBJV78gVuQYaHzFVca+kB0mX0fMW9UFevCOBG50A==", "package/dist/viz-global.js", "Viz.js"),
}
SOURCES = {
    "graphviz": ("https://gitlab.com/api/v4/projects/4207231/packages/generic/graphviz-releases/16.1.0/graphviz-16.1.0.tar.gz", "beea483ab130f456c1c3905f4f2e40778a9c493c3d73ae8012367d552d71ca84"),
    "expat": ("https://github.com/libexpat/libexpat/releases/download/R_2_8_5/expat-2.8.5.tar.gz", "920dde485e15eda0cce8d2310b41d492c534e5e3d89ad407a0b4176dd2ff88fe"),
}
LICENSES = {
    "viz": ("https://raw.githubusercontent.com/mdaines/viz-js/c8ce050d28eb0dc1ed1629ea32ab7f3dc117db0f/LICENSE", "f1fb91bf7cbcb42b2af56949e4fa909e1979d5b57c2826cabacdb4b631457720"),
    "emscripten": ("https://raw.githubusercontent.com/emscripten-core/emscripten/6.0.10/LICENSE", "620a78084fc7ca97c0b5dea9abf891f3ffcadfdbf305276f099c9c4e12fc1d86"),
}


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--cache-dir", type=Path)
    options = args.parse_args()
    DEST.mkdir(parents=True, exist_ok=True)
    def download(url, cache_name):
        cached = options.cache_dir / cache_name if options.cache_dir else None
        return cached.read_bytes() if cached and cached.is_file() else urllib.request.urlopen(url, timeout=45).read()
    def archive(data, member):
        with tarfile.open(fileobj=io.BytesIO(data)) as tar:
            entry = tar.getmember(member)
            if not entry.isfile():
                raise ValueError("Unexpected diagram archive entry")
            return tar.extractfile(entry).read()
    notices = {}
    for name, (version, url, integrity, member, filename) in PACKAGES.items():
        data = download(url, f"snowfolio-{name}.tgz")
        if base64.b64encode(hashlib.sha512(data).digest()).decode() != integrity:
            raise ValueError("Diagram package integrity mismatch: " + name)
        (DEST / filename).write_bytes(archive(data, member))
        if name == "mermaid":
            notices["Mermaid"] = archive(data, "package/LICENSE")
        else:
            (DEST / "Viz-Build-Provenance.json").write_bytes(archive(data, "package/lib/provenance.json"))
        print(name, version, "verified")
    for name, (url, digest) in SOURCES.items():
        data = download(url, f"snowfolio-{name}-source.tgz")
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError("Diagram source integrity mismatch: " + name)
        if name == "graphviz":
            notices["Graphviz"] = archive(data, "graphviz-16.1.0/COPYING")
            notices["Graphviz-rbtree"] = archive(data, "graphviz-16.1.0/lib/rbtree/LICENSE")
        else:
            notices["Expat"] = archive(data, "expat-2.8.5/COPYING")
    for name, (url, digest) in LICENSES.items():
        data = download(url, f"snowfolio-{name}-LICENSE.txt")
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError("Diagram license integrity mismatch: " + name)
        notices["Viz" if name == "viz" else "Emscripten"] = data
    for name, data in notices.items():
        (DEST / (name + "-LICENSE.txt")).write_bytes(data)
        (ROOT / "App/Resources/Licenses" / (name + "-diagram.txt")).write_bytes(data)
    source_notice = """Graphviz 16.1.0 (Eclipse Public License 2.0) and Expat 2.8.5 are included in
Viz.js 3.31.0 as WebAssembly generated by Emscripten 6.0.10.

The complete source releases are available without charge:
https://gitlab.com/api/v4/projects/4207231/packages/generic/graphviz-releases/16.1.0/graphviz-16.1.0.tar.gz
https://github.com/libexpat/libexpat/releases/download/R_2_8_5/expat-2.8.5.tar.gz

The exact Viz.js wrapper, build recipes and any build adaptations are available at:
https://github.com/mdaines/viz-js/tree/c8ce050d28eb0dc1ed1629ea32ab7f3dc117db0f

All original bundled engine notices remain in the adjacent LICENSE files and scripts.
"""
    (DEST / "Diagram-Sources.txt").write_text(source_notice)
    (ROOT / "App/Resources/Licenses/Diagram-Sources.txt").write_text(source_notice)
    provenance = {"packages": {name: {"version": value[0], "source": value[1], "archiveIntegrity": "sha512-" + value[2]} for name, value in PACKAGES.items()},
        "sourceArchives": {name: {"source": value[0], "sha256": value[1]} for name, value in SOURCES.items()},
        "licenseSources": {name: {"source": value[0], "sha256": value[1]} for name, value in LICENSES.items()},
        "runtime": "Bundled Mermaid; Viz.js with embedded WebAssembly Graphviz 16.1.0; no Node or downloads",
        "bundleChanges": [],
        "files": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DEST.iterdir()) if p.name != "Diagram-Provenance.json"}}
    (DEST / "Diagram-Provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


if __name__ == "__main__":
    main()
